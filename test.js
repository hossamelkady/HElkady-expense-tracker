r=p('قبضت ألفين جنيه مرتب');assert.deepStrictEqual([r.type,r.amount,r.category],['income',2000,'دخل']);
r=p('صرفت ٢٥٠ على الكهرباء');assert.deepStrictEqual([r.amount,r.category],[250,'فواتير']);
